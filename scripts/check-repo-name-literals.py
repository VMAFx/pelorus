"""Check for hardcoded upstream repository and container registry name literals.

Refuses 'github.com/vmafx/pelorus' and 'ghcr.io/vmafx/pelorus' (case-insensitive)
in tracked files outside documentation and an explicit allow-list, and the bare
'VMAFx/pelorus' in workflows, where github.repository names the running
repository. A `github.repository == 'VMAFx/pelorus'` gate stays allowed: it keeps
a job upstream-only on purpose.

Usage:
    python3 -I scripts/check-repo-name-literals.py
    python3 -I scripts/check-repo-name-literals.py [path ...]
    python3 -I scripts/check-repo-name-literals.py --self-test
"""

from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import subprocess  # nosec B404 - fixed git argv, no shell, explicit deadline
import sys
import tempfile

DESCRIPTION = "Check for hardcoded upstream repository and container registry name literals."

FORBIDDEN_LITERALS = (
    "github.com/vmafx/pelorus",
    "ghcr.io/vmafx/pelorus",
)

WORKFLOW_PREFIX = ".github/workflows/"
BARE_REPO = re.compile(r"(?<![\w./-])vmafx/pelorus(?!\w)", re.IGNORECASE)
UPSTREAM_GATE = "github.repository == 'vmafx/pelorus'"

ALLOWLIST: dict[str, str] = {
    ".devcontainer/Dockerfile.praetor": "generated by another tool; do not touch",
    ".devcontainer/base/Containerfile": "Containerfile comments and default ARG fallback for upstream source repository",
    ".devcontainer/base/licensing.json": "licence provenance of shipped files names the upstream source",
    ".devcontainer/devcontainer.json": "baseImage digest pin consumes upstream image until fork publishes its own",
    ".github/ISSUE_TEMPLATE/config.yml": "static issue template configuration linking upstream documentation",
    "scripts/bench/record.schema.json": "schema $id URL is a stable identifier",
    "scripts/check-repo-name-literals.py": "repo name guard script defining the checked literals",
    "scripts/release/fixtures/expected-release-notes.txt": "release notes fixture strings",
    "scripts/release/release_notes.py": "release notes self-test fixture strings",
    "scripts/release/write-patch-notice.sh": "upstream default fallback when GITHUB_SERVER_URL/GITHUB_REPOSITORY unset",
    "tools/tester/Containerfile": "Containerfile default ARG fallback for upstream source repository",
    "tools/tester/licensing.json": "licence provenance of shipped files names the upstream source",
    "tools/tester/pelorus_tester_fixtures.py": "USER_AGENT identifies the tool upstream",
    "tools/tester/report.schema.json": "schema $id URL is a stable identifier",
}


class GitListError(RuntimeError):
    """git ls-files could not list tracked files."""


def get_tracked_files(repo_root: pathlib.Path, git: str) -> list[pathlib.Path]:
    """Retrieve git-tracked files via git ls-files -z; raise GitListError on failure."""
    try:
        proc = subprocess.run(  # nosec B603 - fixed git argv; list argv, no shell
            [git, "ls-files", "-z"],
            cwd=repo_root,
            capture_output=True,
            check=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise GitListError(f"git ls-files failed: {exc}") from exc
    try:
        names = proc.stdout.decode("utf-8").split("\0")
    except UnicodeDecodeError as exc:
        raise GitListError(f"git ls-files output is not UTF-8: {exc}") from exc
    return [repo_root / name for name in names if name]


def check_file_content(path: pathlib.Path, rel_path: str) -> list[str]:
    """Scan file lines for forbidden literals, returning list of violation strings."""
    violations: list[str] = []
    try:
        content = path.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        return [f"{rel_path}: could not read: {exc}"]

    is_workflow = rel_path.startswith(WORKFLOW_PREFIX)
    for line_no, line in enumerate(content.splitlines(), start=1):
        # A regex-escaped form (github\\.com/...) names the same repository.
        line_lower = line.lower().replace("\\.", ".")
        for literal in FORBIDDEN_LITERALS:
            if literal in line_lower:
                violations.append(f"{rel_path}:{line_no}: found forbidden literal '{literal}'")
        if is_workflow and UPSTREAM_GATE not in line_lower and BARE_REPO.search(line):
            violations.append(
                f"{rel_path}:{line_no}: found bare repository name 'VMAFx/pelorus'; use github.repository"
            )
    return violations


def check_paths(
    paths: list[pathlib.Path],
    repo_root: pathlib.Path,
    allowlist: dict[str, str],
    check_stale_allowlist: bool = True,
) -> tuple[list[str], list[str]]:
    """Check files against forbidden literals and validate allowlist entries."""
    violations: list[str] = []
    stale_errors: list[str] = []

    for path in paths:
        try:
            rel = path.relative_to(repo_root).as_posix()
        except ValueError:
            rel = path.as_posix()

        if rel.startswith("docs/") or rel.endswith(".md"):
            continue

        file_violations = check_file_content(path, rel)
        if rel not in allowlist:
            violations.extend(file_violations)

    if check_stale_allowlist:
        for allow_path in sorted(allowlist.keys()):
            full_path = repo_root / allow_path
            if not full_path.is_file():
                stale_errors.append(f"stale allow-list entry: '{allow_path}' does not exist on disk")
                continue
            has_literal = False
            try:
                content = full_path.read_text(encoding="utf-8", errors="replace")
                content_lower = content.lower()
                for literal in FORBIDDEN_LITERALS:
                    if literal in content_lower:
                        has_literal = True
                        break
            except OSError:
                has_literal = False

            if not has_literal:
                stale_errors.append(
                    f"stale allow-list entry: '{allow_path}' contains none of the forbidden literals"
                )

    return violations, stale_errors


# (label, files {path: text}, allow-list, check stale entries, expected finding or None)
_SELF_CASES: tuple[tuple[str, dict[str, str], dict[str, str], bool, str | None], ...] = (
    (
        "workflow literal",
        {".github/workflows/publish.yml": "name: Test\nenv:\n  IMAGE: ghcr.io/vmafx/pelorus\n"},
        {},
        False,
        ".github/workflows/publish.yml:3: found forbidden literal 'ghcr.io/vmafx/pelorus'",
    ),
    (
        "allow-listed file",
        {"tools/allowed.py": 'REPO = "https://github.com/vmafx/pelorus"\n'},
        {"tools/allowed.py": "valid allowlist entry"},
        True,
        None,
    ),
    (
        "stale allow-list entry",
        {"tools/clean.py": 'MSG = "clean content"\n'},
        {"tools/clean.py": "stale allowlist reason"},
        True,
        "stale allow-list entry: 'tools/clean.py' contains none of the forbidden literals",
    ),
    (
        "docs and markdown",
        {"docs/readme.txt": "See https://github.com/VMAFx/pelorus\n", "NOTES.md": "Image is ghcr.io/vmafx/pelorus\n"},
        {},
        False,
        None,
    ),
    (
        "bare name in workflow",
        {".github/workflows/verify.yml": "run: gh attestation verify x -R VMAFx/pelorus\n"},
        {},
        False,
        ".github/workflows/verify.yml:1: found bare repository name 'VMAFx/pelorus'",
    ),
    (
        "regex-escaped literal",
        {".github/workflows/sign.yml": "--certificate-identity-regexp '^https://github\\.com/VMAFx/pelorus/'\n"},
        {},
        False,
        ".github/workflows/sign.yml:1: found forbidden literal 'github.com/vmafx/pelorus'",
    ),
    (
        "upstream-only gate",
        {".github/workflows/nightly.yml": "if: github.repository == 'VMAFx/pelorus'\n"},
        {},
        False,
        None,
    ),
)


def _run_case(
    tmp_dir: pathlib.Path,
    case: tuple[str, dict[str, str], dict[str, str], bool, str | None],
) -> str | None:
    """Plant one case in its own tree; return a failure text or None."""
    label, files, allowlist, stale, expected = case
    root = tmp_dir / label.replace(" ", "-")
    paths: list[pathlib.Path] = []
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        paths.append(path)
    violations, stale_errors = check_paths(paths, root, allowlist, check_stale_allowlist=stale)
    found = violations + stale_errors
    if expected is None:
        return f"{label}: refused: {found}" if found else None
    if not any(expected in item for item in found):
        return f"{label}: expected {expected!r}, got {found}"
    print(f"planted case '{label}' failing output:")
    for item in found:
        print(f"  {item}")
    return None


def run_self_test() -> int:
    """Run the planted cases: violations, allow-list, stale entry, docs, bare workflow name."""
    with tempfile.TemporaryDirectory() as tmp_dir_str:
        for case in _SELF_CASES:
            failure = _run_case(pathlib.Path(tmp_dir_str), case)
            if failure:
                print(f"self-test FAIL: {failure}", file=sys.stderr)
                return 1
    print("check-repo-name-literals self-test: ok")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=DESCRIPTION)
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="Run self-test on planted cases",
    )
    parser.add_argument(
        "paths",
        nargs="*",
        type=pathlib.Path,
        help="Optional files to check (defaults to git-tracked files)",
    )
    args = parser.parse_args(argv)

    if args.self_test:
        return run_self_test()

    repo_root = pathlib.Path(__file__).resolve().parent.parent

    if args.paths:
        files = [p.resolve() for p in args.paths]
        check_stale = False
    else:
        git = shutil.which("git")
        if git is None or not pathlib.Path(git).is_file():
            print(
                "check-repo-name-literals: git not on PATH; pass files or use --self-test",
                file=sys.stderr,
            )
            return 2
        try:
            files = get_tracked_files(repo_root, git)
        except GitListError as exc:
            print(f"check-repo-name-literals: {exc}", file=sys.stderr)
            return 2
        check_stale = True

    violations, stale_errors = check_paths(
        files, repo_root, ALLOWLIST, check_stale_allowlist=check_stale
    )

    if violations or stale_errors:
        for err in violations:
            print(f"check-repo-name-literals: {err}", file=sys.stderr)
        for err in stale_errors:
            print(f"check-repo-name-literals: {err}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
