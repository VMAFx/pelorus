"""Generate the per-encoder AVOption name tables for the encode record (ADR-0200).

An encoder's table lists the AVOption names that reach its encode:

- every non-constant private option of the encoder (avoption-probe output);
- every AVCodecContext option whose field the encoder's FFmpeg source reads
  as `avctx-><field>` (options_table.h maps option name to field).

pel_encode_options_from_ffmpeg stores a name in the table under `params` and
any other name under `unknown_params`; the ignore list and the clash pairs
live in libpelorus/src/encode_avoptions.c, not here.

Usage (FFmpeg source and library at the pin in build-config.env):

  cc -o avoption-probe scripts/encode-options/avoption-probe.c -lavcodec -lavutil
  ./avoption-probe libx264 libx265 libsvtav1 libaom-av1 h264_nvenc hevc_nvenc \\
      av1_nvenc h264_qsv hevc_qsv av1_qsv h264_vaapi hevc_vaapi av1_vaapi \\
      h264_vulkan hevc_vulkan av1_vulkan > avoptions.tsv
  python3 -I scripts/encode-options/gen-avoption-tables.py avoptions.tsv \\
      /path/to/ffmpeg n9.0.2 libpelorus/src/encode_avoptions_tables.c
"""

import hashlib
import pathlib
import re
import sys
from typing import NoReturn

# encoder -> (dialect enum or None, option-string AVOption or None, source files)
_X264 = ("PEL_ENCODE_OPTIONS_X264", "x264-params", ["libx264.c"])
_X265 = ("PEL_ENCODE_OPTIONS_X265", "x265-params", ["libx265.c"])
_SVT = ("PEL_ENCODE_OPTIONS_SVTAV1", "svtav1-params", ["libsvtav1.c"])
_AOM = ("PEL_ENCODE_OPTIONS_AOM", "aom-params", ["libaomenc.c"])
_VAAPI = ["vaapi_encode.c", "hw_base_encode.c"]
_VULKAN = ["vulkan_encode.c", "hw_base_encode.c"]
ENCODERS = {
    "libx264": _X264,
    "libx265": _X265,
    "libsvtav1": _SVT,
    "libaom-av1": _AOM,
    "h264_nvenc": (None, None, ["nvenc.c", "nvenc_h264.c"]),
    "hevc_nvenc": (None, None, ["nvenc.c", "nvenc_hevc.c"]),
    "av1_nvenc": (None, None, ["nvenc.c", "nvenc_av1.c"]),
    "h264_qsv": (None, None, ["qsvenc.c", "qsvenc_h264.c"]),
    "hevc_qsv": (None, None, ["qsvenc.c", "qsvenc_hevc.c"]),
    "av1_qsv": (None, None, ["qsvenc.c", "qsvenc_av1.c"]),
    "h264_vaapi": (None, None, _VAAPI + ["vaapi_encode_h264.c", "hw_base_encode_h264.c"]),
    "hevc_vaapi": (None, None, _VAAPI + ["vaapi_encode_h265.c", "hw_base_encode_h265.c"]),
    "av1_vaapi": (None, None, _VAAPI + ["vaapi_encode_av1.c"]),
    "h264_vulkan": (None, None, _VULKAN + ["vulkan_encode_h264.c", "hw_base_encode_h264.c"]),
    "hevc_vulkan": (None, None, _VULKAN + ["vulkan_encode_h265.c", "hw_base_encode_h265.c"]),
    "av1_vulkan": (None, None, _VULKAN + ["vulkan_encode_av1.c"]),
}

# {"name", "help" ["help" ...], OFFSET(field) ...
_OPTION_RE = re.compile(
    r'\{\s*"([^"]+)"\s*,\s*(?:(?:"(?:[^"\\]|\\.)*"\s*)+|NULL\s*),\s*OFFSET\((\w+)\)'
)
_NAME_RE = re.compile(r"^[!#-\[\]-~]{1,56}$")


class GenError(Exception):
    """Bad input; main() reports it and returns 1."""


def fail(msg) -> NoReturn:
    raise GenError(msg)


def read_probe(path):
    owners = {}
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        cols = line.split("\t")
        if len(cols) < 3:
            fail(f"{path}:{lineno}: fewer than 3 columns")
        if cols[2] == "const":
            continue
        if not _NAME_RE.match(cols[1]) or ":" in cols[1]:
            fail(f"{path}:{lineno}: option name {cols[1]!r} is not a record key")
        owners.setdefault(cols[0], set()).add(cols[1])
    return owners


def avctx_fields(options_table):
    fields = {}
    for name, field in _OPTION_RE.findall(options_table.read_text(encoding="utf-8")):
        fields.setdefault(name, field)
    return fields


def honoured(avctx_names, fields, sources):
    text = "".join(s.read_text(encoding="utf-8") for s in sources)
    out = set()
    for name in avctx_names:
        field = fields.get(name)
        if field is None:
            fail(f"AVCodecContext option {name!r} has no OFFSET() in options_table.h")
        if re.search(r"\bavctx->" + re.escape(field) + r"\b", text):
            out.add(name)
    return out


def c_name(encoder):
    return "k_" + re.sub(r"[^a-z0-9]", "_", encoder) + "_names"


def render(tables, ffmpeg_tag, digests):
    lines = [
        "/*",
        " * Copyright 2026 Lusoris",
        # REUSE-IgnoreStart
        " * SPDX-License-Identifier: EUPL-1.2",
        # REUSE-IgnoreEnd
        " *",
        " * Generated by scripts/encode-options/gen-avoption-tables.py; do not edit.",
        f" * FFmpeg {ffmpeg_tag}. Inputs (sha256):",
    ]
    lines += [f" *   {d}  {n}" for n, d in digests]
    lines += [
        " */",
        "",
        '#include "encode_options_internal.h"',
        "",
    ]
    for enc, names in tables.items():
        lines.append(f"static const char *const {c_name(enc)}[] = {{")
        lines += [f'    "{n}",' for n in names]
        lines += ["};", ""]
    lines.append("static const PelAvoptEncoder k_encoders[] = {")
    for enc, names in tables.items():
        dialect, params_key, _ = ENCODERS[enc]
        d = dialect if dialect else "(pel_encode_options_dialect)0"
        p = f'"{params_key}"' if params_key else "NULL"
        lines.append(f'    {{"{enc}", {d}, {p}, {c_name(enc)}, {len(names)}u}},')
    lines += [
        "};",
        "",
        "const PelAvoptEncoder *pel_encode_avoptions_encoders(size_t *out_count)",
        "{",
        "    *out_count = sizeof(k_encoders) / sizeof(k_encoders[0]);",
        "    return k_encoders;",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 5:
        fail("usage: gen-avoption-tables.py PROBE.tsv FFMPEG_SRC FFMPEG_TAG OUT.c")
    probe = pathlib.Path(argv[1])
    src = pathlib.Path(argv[2]) / "libavcodec"
    owners = read_probe(probe)
    if "avctx" not in owners:
        fail("probe output has no avctx rows")
    options_table = src / "options_table.h"
    fields = avctx_fields(options_table)
    inputs = [probe, options_table]
    tables = {}
    for enc, (_, params_key, files) in ENCODERS.items():
        if enc not in owners:
            fail(f"probe output has no rows for {enc}")
        sources = [src / f for f in files]
        for s in sources:
            if not s.is_file():
                fail(f"missing source {s}")
            if s not in inputs:
                inputs.append(s)
        names = owners[enc] | honoured(owners["avctx"], fields, sources)
        if params_key and params_key not in names:
            fail(f"{enc} has no {params_key} AVOption")
        tables[enc] = sorted(names, key=lambda n: n.encode("ascii"))
    digests = [
        (p.name, hashlib.sha256(p.read_bytes()).hexdigest()) for p in inputs
    ]
    pathlib.Path(argv[4]).write_text(render(tables, argv[3], digests), encoding="utf-8")
    return 0


if __name__ == "__main__":
    try:
        STATUS = main(sys.argv)
    except GenError as err:
        sys.stderr.write(f"gen-avoption-tables: {err}\n")
        STATUS = 1
    sys.exit(STATUS)
