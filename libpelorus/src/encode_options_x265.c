static int opt_def_cmp(const void *a, const void *b)
{
    const char *key = (const char *)a;
    const PelEncodeOptDef *def = (const PelEncodeOptDef *)b;
    return strcmp(key, def->name);
}

const PelEncodeOptDef *pel_encode_options_x265_lookup(const char *name)
{
    if (!name) {
        return NULL;
    }
    return (const PelEncodeOptDef *)bsearch(name, k_x265_options,
                                            sizeof(k_x265_options) / sizeof(k_x265_options[0]),
                                            sizeof(k_x265_options[0]), opt_def_cmp);
}

const PelEncodeOptDef *pel_encode_options_x265_table(size_t *out_count)
{
    if (out_count) {
        *out_count = sizeof(k_x265_options) / sizeof(k_x265_options[0]);
    }
    return k_x265_options;
}
